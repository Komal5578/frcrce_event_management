// ---------------------------------------------------------------------------
// 3. FACT-STRICT ROUTE DIRECTIONS
// Built strictly from stated facts. Never invents turns like "turn left/right".
// ---------------------------------------------------------------------------
export function getFactStrictRouteDirections(
  targetEntity: FloorEntity
): {
  floorLabel: string;
  howToReach: string;
  roomGuidance: string;
} {
  const floor =
    campusFloors.find((f) => f.id === targetEntity.floorId) ?? campusFloors[0];

  let roomGuidance = "";

  if (targetEntity.specialPlacement) {
    roomGuidance = `Located ${targetEntity.specialPlacement}.`;
  } else if (targetEntity.floorId === "ground") {
    roomGuidance = "Located on the ground floor at the main entrance.";
  } else if (targetEntity.floorId === "floor-9") {
    roomGuidance = "The entire 9th floor is Samvaad.";
  } else if (targetEntity.floorId === "floor-2" && targetEntity.type === "library") {
    roomGuidance = "The library covers most of the 2nd floor.";
  } else if (targetEntity.floorId === "floor-1" && targetEntity.id === "1f-office") {
    roomGuidance = "The Office is located in front of the 2 staff lifts.";
  } else if (targetEntity.floorId === "floor-1" && targetEntity.type === "canteen") {
    roomGuidance = "The cafeteria and open canteen are located near two of the student lifts.";
  } else if (targetEntity.floorId === "floor-1" && targetEntity.id === "1f-chem-lab") {
    roomGuidance = "The Chemistry Lab is located near two of the student lifts.";
  } else {
    roomGuidance = `From the lifts, proceed into the floor lane to reach ${targetEntity.name}.`;
  }

  return {
    floorLabel: floor.label,
    howToReach: floor.howToReach,
    roomGuidance,
  };
}
